"""Turn a detected signal into an alert: order idea, position size in GBP, reasons, history, mini-chart."""
from __future__ import annotations

from dataclasses import asdict

import numpy as np
import pandas as pd

from edgelab.patterns.base import PATTERNS, Signal, TradePlan
from edgelab.risk import analyse_position, units_for_risk, value_per_price_unit
from edgelab.timeutil import timeframe_minutes

CHART_BARS = 70
DISCLAIMER = ("Educational idea generated by a fixed rule - not financial advice. EdgeLab never places orders; "
              "you decide whether to act, and most short-term setups lose money after costs.")


def passes_filters(sig: Signal, ctx, settings) -> bool:
    if sig.plan is None or sig.direction not in ("long", "short"):
        return False
    enabled = settings.enabled_patterns
    if enabled and sig.pattern not in enabled:
        return False
    if settings.notify_only_in_window and ctx.intraday and not ctx.in_window[sig.i]:
        return False
    q = settings.alert_quality
    if q == "strict" and sig.cautions:
        return False
    if q == "normal" and len(sig.cautions) > 1:
        return False
    return True


def position_info(sig: Signal, inst, settings, balance: float, conv) -> dict:
    p = sig.plan
    broker = settings.broker()
    vpu = value_per_price_unit(inst, 1.0, p.entry, conv, settings.account_currency)
    if vpu is None:
        return {}
    if settings.forex_sizing == "fixed":
        units = int(settings.forex_fixed_units)
    else:
        units = units_for_risk(balance * settings.risk_pct / 100, p.risk, vpu, broker.min_units)
    if units <= 0:
        return {"units": 0}
    r = analyse_position(inst, units, p.entry, balance=balance, risk_pct=settings.risk_pct, broker=broker, conv=conv,
                         ccy=settings.account_currency, stop_distance=p.risk, target_distance=p.risk * p.target_r)
    return {"units": units, "lots": units / 100_000, "risk": r.total_risk, "risk_pct": r.risk_pct,
            "reward": r.reward, "margin": r.margin_required, "free_margin": r.free_margin, "costs": r.costs.total,
            "fits_rule": bool(r.total_risk <= r.risk_limit * 1.0001), "risk_limit": r.risk_limit,
            "rule_pct": settings.risk_pct,
            "units_for_limit": r.units_for_limit, "currency": settings.account_currency,
            "pip_value": r.pip_value, "stop_pips": p.risk / inst.pip if inst.is_forex else None}


def history_before(analysis, pattern: str, direction: str, before_i: int | None = None) -> dict | None:
    """Stats for a pattern+direction from trades that had FINISHED before bar `before_i` (no look-ahead).

    before_i=None uses every finished trade (e.g. your stored history when scanning live)."""
    from edgelab.patterns.stats import summarise

    outs = [o for s, o in zip(analysis.signals, analysis.outcomes)
            if o is not None and s.pattern == pattern and s.direction == direction
            and o.exit_i is not None and (before_i is None or o.exit_i < before_i)]
    if not outs:
        return None
    st = summarise(pattern, direction, outs)
    return {k: (None if isinstance(v, float) and not np.isfinite(v) else v) for k, v in asdict(st).items()}


def build_payload(sig: Signal, ctx, inst, timeframe: str, settings, balance: float, conv, stats: dict | None,
                  stats_source: str, mode: str) -> dict:
    i0 = max(0, sig.i - CHART_BARS)
    for p, _, _ in sig.points:
        i0 = max(0, min(i0, p - 5))
    if sig.zone:
        i0 = max(0, min(i0, sig.zone[0] - 5))
    seg = ctx.df.iloc[i0:sig.i + 1]
    cols = [c for c in ("open", "high", "low", "close", "volume", "vwap", "ema9", "ema20") if c in seg]
    bars = {"ts": [int(t.timestamp()) for t in seg.index], **{c: [None if pd.isna(v) else float(v) for v in seg[c]]
                                                              for c in cols}}
    ts_of = lambda k: int(ctx.df.index[k].timestamp())  # noqa: E731
    info = PATTERNS[sig.pattern]
    return {
        "mode": mode, "symbol": inst.symbol, "timeframe": timeframe, "pattern": sig.pattern, "title": sig.title,
        "direction": sig.direction, "bar_ts": ts_of(sig.i), "price": sig.price, "decimals": inst.decimals,
        "plan": asdict(sig.plan), "reasons": list(sig.reasons), "cautions": list(sig.cautions),
        "levels": {k: float(v) for k, v in sig.levels.items()},
        "zone": None if not sig.zone else [ts_of(sig.zone[0]), ts_of(sig.zone[1]), float(sig.zone[2]), float(sig.zone[3])],
        "points": [[ts_of(p), float(pr), lab] for p, pr, lab in sig.points],
        "position": position_info(sig, inst, settings, balance, conv), "stats": stats, "stats_source": stats_source,
        "bars": bars, "confirm": info.confirm, "invalidate": info.invalidate, "meaning": info.meaning,
        "expiry_minutes": int(sig.plan.expiry_bars * timeframe_minutes(timeframe)),
    }


def payload_frame_and_signal(pl: dict) -> tuple[pd.DataFrame, Signal]:
    """Rebuild the mini-chart data and a Signal (positions relative to that data) from a stored alert."""
    b = dict(pl["bars"])
    idx = pd.to_datetime(b.pop("ts"), unit="s", utc=True)
    df = pd.DataFrame(b, index=idx).astype(float)
    pos = {int(t.timestamp()): k for k, t in enumerate(df.index)}
    near = lambda ts: pos.get(int(ts), int(np.clip(df.index.searchsorted(pd.Timestamp(ts, unit="s", tz="UTC")), 0, len(df) - 1)))  # noqa: E731
    zone = None
    if pl.get("zone"):
        z = pl["zone"]
        zone = (near(z[0]), near(z[1]), z[2], z[3])
    sig = Signal(pl["pattern"], pl["direction"], len(df) - 1, df.index[-1], pl["price"], pl["plan"]["stop"],
                 levels=pl["levels"], zone=zone, points=[(near(t), p, lab) for t, p, lab in pl["points"]],
                 reasons=pl["reasons"], cautions=pl["cautions"], plan=TradePlan(**pl["plan"]))
    return df, sig


def fmt_price(x: float, decimals: int) -> str:
    return f"{x:.{decimals}f}"


def headline(pl: dict) -> str:
    p = pl["plan"]
    return f"{pl['symbol']} {pl['timeframe']} - {pl['title']}: {p['order_type']} {fmt_price(p['entry'], pl['decimals'])}"


def desktop_text(pl: dict) -> str:
    p, d = pl["plan"], pl["decimals"]
    pos = pl.get("position") or {}
    risk = (f" Risk {pos['currency']} {pos['risk']:.2f}" + (f" ({pos['risk_pct']:.2f}%)" if pos.get("risk_pct") is not None
                                                             else "") + "." if pos.get("risk") else "")
    why = pl["reasons"][0] if pl["reasons"] else ""
    sim = "[SIMULATION] " if pl.get("mode") == "simulation" else ""
    return (f"{sim}{p['order_type']} {fmt_price(p['entry'], d)} | SL {fmt_price(p['stop'], d)} | "
            f"TP {fmt_price(p['target'], d)} ({p['target_r']:g}R).{risk} Why: {why}. Open EdgeLab for the chart.")
